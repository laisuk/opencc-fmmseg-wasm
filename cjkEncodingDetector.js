/*
 * Pure JavaScript CJK/Unicode encoding detector.
 *
 * Ported from the project's CjkEncodingDetector.cs so the browser demo can
 * detect text-file encodings without calling into WebAssembly.
 *
 * Detection order:
 * BOM -> ASCII -> strict UTF-8 -> BOM-less UTF-16 heuristic ->
 * Big5/GB18030/Shift-JIS statistical fallback -> unknown.
 *
 * GB2312 and GBK are reported as "gb18030", matching TextDecoder usage.
 *
 * The Big5/GB18030 statistical models are derived from uchardet 0.0.5 /
 * Mozilla Universal Charset Detector. Keep the corresponding upstream
 * licensing notices when redistributing this port.
 */

const MAX_HEURISTIC_SAMPLE_SIZE = 128 * 1024;
const MIN_LEGACY_CONFIDENCE = 0.20;
const MIN_LEGACY_MARGIN = 0.05;

const STATE_START = 0;
const STATE_ERROR = 1;
const STATE_ITS_ME = 2;

export function detectCjkEncoding(data) {
    if (!(data instanceof Uint8Array)) {
        throw new TypeError("data must be a Uint8Array");
    }

    const count = data.length;
    if (count === 0) {
        return unknown();
    }

    if (startsWith(data, 0xEF, 0xBB, 0xBF)) {
        return result("utf-8", "UTF-8 BOM", 3, 1.0);
    }

    if (startsWith(data, 0xFF, 0xFE)) {
        return result("utf-16le", "UTF-16 LE BOM", 2, 1.0);
    }

    if (startsWith(data, 0xFE, 0xFF)) {
        return result("utf-16be", "UTF-16 BE BOM", 2, 1.0);
    }

    const utf8Kind = classifyUtf8(data);
    if (utf8Kind !== null) {
        return result("utf-8", utf8Kind === "ascii" ? "ASCII" : "UTF-8", 0, 1.0);
    }

    if (looksLikeUtf16(data, 1)) {
        return result("utf-16le", "UTF-16 LE", 0, 0.90);
    }

    if (looksLikeUtf16(data, 0)) {
        return result("utf-16be", "UTF-16 BE", 0, 0.90);
    }

    return detectChineseLegacy(data);
}

function result(encoding, name, bomSize, confidence) {
    return {
        encoding,
        name,
        bomSize,
        confidence,
        detected: true
    };
}

function unknown() {
    return {
        encoding: null,
        name: "Unknown",
        bomSize: 0,
        confidence: 0,
        detected: false
    };
}

function startsWith(data, ...bytes) {
    if (data.length < bytes.length) {
        return false;
    }

    for (let i = 0; i < bytes.length; i++) {
        if (data[i] !== bytes[i]) {
            return false;
        }
    }

    return true;
}

function classifyUtf8(data) {
    let i = 0;
    let ascii = true;

    while (i < data.length) {
        const c0 = data[i];

        if (c0 <= 0x7F) {
            i++;
            continue;
        }

        ascii = false;

        if (c0 >= 0xC2 && c0 <= 0xDF) {
            if (i + 1 >= data.length || (data[i + 1] & 0xC0) !== 0x80) {
                return null;
            }
            i += 2;
            continue;
        }

        if (c0 >= 0xE0 && c0 <= 0xEF) {
            if (i + 2 >= data.length) {
                return null;
            }

            const c1 = data[i + 1];
            const c2 = data[i + 2];

            if ((c2 & 0xC0) !== 0x80) {
                return null;
            }

            if (c0 === 0xE0) {
                if (c1 < 0xA0 || c1 > 0xBF) return null;
            } else if (c0 === 0xED) {
                if (c1 < 0x80 || c1 > 0x9F) return null;
            } else if ((c1 & 0xC0) !== 0x80) {
                return null;
            }

            i += 3;
            continue;
        }

        if (c0 >= 0xF0 && c0 <= 0xF4) {
            if (i + 3 >= data.length) {
                return null;
            }

            const c1 = data[i + 1];
            const c2 = data[i + 2];
            const c3 = data[i + 3];

            if ((c2 & 0xC0) !== 0x80 || (c3 & 0xC0) !== 0x80) {
                return null;
            }

            if (c0 === 0xF0) {
                if (c1 < 0x90 || c1 > 0xBF) return null;
            } else if (c0 === 0xF4) {
                if (c1 < 0x80 || c1 > 0x8F) return null;
            } else if ((c1 & 0xC0) !== 0x80) {
                return null;
            }

            i += 4;
            continue;
        }

        return null;
    }

    return ascii ? "ascii" : "utf8";
}

function looksLikeUtf16(data, zeroByteIndex) {
    const count = data.length;

    if (count < 4 || (count & 1) !== 0) {
        return false;
    }

    const sampleCount = Math.min(count, MAX_HEURISTIC_SAMPLE_SIZE) & ~1;
    let zeroBytes = 0;
    let pairs = 0;

    for (let i = 0; i < sampleCount; i += 2) {
        const first = data[i];
        const second = data[i + 1];
        const zeroByte = zeroByteIndex === 0 ? first : second;
        const otherByte = zeroByteIndex === 0 ? second : first;

        if (zeroByte === 0 && otherByte !== 0) {
            zeroBytes++;
        }

        pairs++;
    }

    return pairs !== 0 && Math.trunc(zeroBytes * 100 / pairs) >= 60;
}

function detectChineseLegacy(data) {
    const sampleCount = Math.min(data.length, MAX_HEURISTIC_SAMPLE_SIZE);

    const big5Confidence = probeBig5(data, sampleCount);
    const gb18030Confidence = probeGb18030(data, sampleCount);
    const shiftJisConfidence = probeShiftJis(data, sampleCount);

    const best = Math.max(big5Confidence, gb18030Confidence, shiftJisConfidence);
    const second = big5Confidence + gb18030Confidence + shiftJisConfidence - best -
        Math.min(big5Confidence, gb18030Confidence, shiftJisConfidence);

    if (best < MIN_LEGACY_CONFIDENCE || best - second < MIN_LEGACY_MARGIN) {
        return unknown();
    }

    if (best === big5Confidence) return result("big5", "Big5", 0, best);
    if (best === gb18030Confidence) return result("gb18030", "GB18030", 0, best);
    return result("shift_jis", "Shift-JIS", 0, best);
}

function probeBig5(data, count) {
    const stateMachine = new CodingStateMachine(
        BIG5_CLASS_TABLE, 5, BIG5_STATE_TABLE, BIG5_CHAR_LEN_TABLE);

    const distribution = new DistributionAnalysis(
        BIG5_FREQUENT_BITS, 5376, 0.75, getBig5Order);

    feedProber(data, count, stateMachine, distribution);
    return distribution.getConfidence();
}

function probeGb18030(data, count) {
    const stateMachine = new CodingStateMachine(
        GB18030_CLASS_TABLE, 7, GB18030_STATE_TABLE, GB18030_CHAR_LEN_TABLE);

    const distribution = new DistributionAnalysis(
        GB2312_FREQUENT_BITS, 3760, 0.90, getGb2312Order);

    feedProber(data, count, stateMachine, distribution);
    return distribution.getConfidence();
}


function probeShiftJis(data, count) {
    const stateMachine = new CodingStateMachine(
        SHIFT_JIS_CLASS_TABLE, 6, SHIFT_JIS_STATE_TABLE, SHIFT_JIS_CHAR_LEN_TABLE);
    const distribution = new DistributionAnalysis(
        JIS_FREQUENT_BITS, 4368, 3.0, getShiftJisOrder);
    const context = new JapaneseContextAnalysis();

    for (let i = 0; i < count; i++) {
        const state = stateMachine.nextState(data[i]);
        if (state === STATE_ITS_ME) break;
        if (state !== STATE_START) continue;

        const charLen = stateMachine.currentCharLen;
        const charStart = i + 1 - charLen;
        if (charLen === 2 && charStart >= 0) {
            const first = data[charStart];
            const second = data[charStart + 1];
            context.handleOneChar(first, second);
            distribution.handleOneChar(first, second);
        } else {
            context.handleNonHiragana();
        }
    }
    return Math.max(context.getConfidence(), distribution.getConfidence());
}

class JapaneseContextAnalysis {
    constructor() {
        this.relationSamples = new Uint32Array(6);
        this.totalRelations = 0;
        this.lastCharOrder = -1;
        this.done = false;
    }

    handleOneChar(first, second) {
        if (this.totalRelations > 1000) this.done = true;
        if (this.done) return;
        const order = getShiftJisHiraganaOrder(first, second);
        if (order >= 0 && this.lastCharOrder >= 0) {
            this.totalRelations++;
            this.relationSamples[JAPANESE_CONTEXT[this.lastCharOrder * 83 + order]]++;
        }
        this.lastCharOrder = order;
    }

    handleNonHiragana() {
        this.lastCharOrder = -1;
    }

    getConfidence() {
        if (this.totalRelations <= 4) return -1.0;
        return (this.totalRelations - this.relationSamples[0]) / this.totalRelations;
    }
}

function getShiftJisOrder(first, second) {
    let order;
    if (first >= 0x81 && first <= 0x9F) order = 188 * (first - 0x81);
    else if (first >= 0xE0 && first <= 0xEF) order = 188 * (first - 0xE0 + 31);
    else return -1;
    order += second - 0x40;
    if (second > 0x7F) order--;
    return order;
}

function getShiftJisHiraganaOrder(first, second) {
    return first === 0x82 && second >= 0x9F && second <= 0xF1
        ? second - 0x9F : -1;
}

function feedProber(data, count, stateMachine, distribution) {
    for (let i = 0; i < count; i++) {
        const state = stateMachine.nextState(data[i]);

        if (state === STATE_ITS_ME) {
            break;
        }

        if (state !== STATE_START) {
            continue;
        }

        const charLen = stateMachine.currentCharLen;
        if (charLen === 2 && i > 0) {
            distribution.handleOneChar(data[i - 1], data[i]);
        }
    }
}

class DistributionAnalysis {
    static MINIMUM_DATA_THRESHOLD = 4;

    constructor(frequentBits, tableSize, typicalDistributionRatio, getOrder) {
        this.frequentBits = frequentBits;
        this.tableSize = tableSize;
        this.typicalDistributionRatio = typicalDistributionRatio;
        this.getOrder = getOrder;
        this.totalChars = 0;
        this.freqChars = 0;
    }

    handleOneChar(first, second) {
        const order = this.getOrder(first, second);
        if (order < 0) {
            return;
        }

        this.totalChars++;

        if (order < this.tableSize && isFrequent(this.frequentBits, order)) {
            this.freqChars++;
        }
    }

    getConfidence() {
        if (this.totalChars <= 0 ||
            this.freqChars <= DistributionAnalysis.MINIMUM_DATA_THRESHOLD) {
            return 0.01;
        }

        if (this.totalChars === this.freqChars) {
            return 0.99;
        }

        const ratio =
            this.freqChars /
            ((this.totalChars - this.freqChars) * this.typicalDistributionRatio);

        return ratio < 0.99 ? ratio : 0.99;
    }
}

class CodingStateMachine {
    constructor(classTable, classFactor, stateTable, charLenTable) {
        this.classTable = classTable;
        this.classFactor = classFactor;
        this.stateTable = stateTable;
        this.charLenTable = charLenTable;
        this.currentState = STATE_START;
        this.currentCharLen = 0;
    }

    nextState(value) {
        const byteClass = this.classTable[value];

        if (this.currentState === STATE_START) {
            this.currentCharLen = this.charLenTable[byteClass];
        }

        this.currentState =
            this.stateTable[this.currentState * this.classFactor + byteClass];

        return this.currentState;
    }
}

function getGb2312Order(first, second) {
    if (first >= 0xB0 && second >= 0xA1) {
        return 94 * (first - 0xB0) + second - 0xA1;
    }

    return -1;
}

function getBig5Order(first, second) {
    if (first < 0xA4) {
        return -1;
    }

    if (second >= 0xA1) {
        return 157 * (first - 0xA4) + second - 0xA1 + 63;
    }

    return 157 * (first - 0xA4) + second - 0x40;
}

function isFrequent(bits, order) {
    return (bits[order >>> 5] & (1 << (order & 31))) !== 0;
}

